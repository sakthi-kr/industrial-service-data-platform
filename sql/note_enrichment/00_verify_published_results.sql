USE ROLE ISP_TRANSFORMER;
USE WAREHOUSE INDUSTRIAL_SERVICE_WH;
USE DATABASE INDUSTRIAL_SERVICE_DB;

SHOW TABLES LIKE 'NOTE_ENRICHMENT_RESULTS' IN SCHEMA STAGING;

SELECT
  MODEL_VERSION,
  COUNT(*) AS STORED_ROWS,
  COUNT(DISTINCT NOTE_ID) AS DISTINCT_NOTES,
  SUM(IFF(OUTPUT_VALID, 0, 1)) AS INVALID_OUTPUTS
FROM STAGING.NOTE_ENRICHMENT_RESULTS
GROUP BY MODEL_VERSION
ORDER BY MODEL_VERSION;

SHOW TABLES LIKE 'MART_TECHNICIAN_NOTE_ENRICHMENT' IN SCHEMA ANALYTICS;

SELECT
  MODEL_VERSION,
  COUNT(*) AS MART_ROWS,
  COUNT(DISTINCT NOTE_ID) AS DISTINCT_NOTES
FROM ANALYTICS.MART_TECHNICIAN_NOTE_ENRICHMENT
GROUP BY MODEL_VERSION
ORDER BY MODEL_VERSION;
